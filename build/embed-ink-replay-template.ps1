<# Regenerates the VBA payload from the reviewed, macro-free animation template.
   PowerPoint's VBA enum cannot create Ink Replay/Rewind. Copying these native
   effects preserves their drawProgress behavior and works in saved PPTX files. #>
$ErrorActionPreference='Stop'
$repoRoot=Split-Path -Parent $PSScriptRoot
$bytes=[IO.File]::ReadAllBytes((Join-Path $repoRoot 'build/templates/InkReplayTemplate.pptx'))
$base64=[Convert]::ToBase64String($bytes)
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('Attribute VB_Name = "EZHighlightReplayData"')
$lines.Add('Option Explicit')
$lines.Add("' Generated by build/embed-ink-replay-template.ps1; do not hand-edit.")
$lines.Add("' Macro-free PowerPoint template: native Replay and Rewind, one slide each.")
$lines.Add('Public Function InkReplayTemplateBase64() As String')
$lines.Add('    Dim data As String')
for($i=0;$i -lt $base64.Length;$i+=700){
 $chunk=$base64.Substring($i,[Math]::Min(700,$base64.Length-$i))
 $lines.Add('    data = data & "'+$chunk+'"')
}
$lines.Add('    InkReplayTemplateBase64 = data')
$lines.Add('End Function')
[IO.File]::WriteAllLines((Join-Path $repoRoot 'Modules/EZHighlightReplayData.bas'),$lines,[Text.Encoding]::ASCII)
Write-Output ('Embedded '+$bytes.Length+' bytes')
